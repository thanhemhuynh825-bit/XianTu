/* 上回收尾：最近一条叙事的结尾（衔接锚点，防止场景断片） */
function lastBeat(s) {
  const log = (s.log || []).filter(l => l && l.a);
  const last = log[log.length - 1];
  if (!last) return '';
  const text = String(last.a).replace(/\*+/g, '').replace(/\s+/g, ' ').trim();
  return text.slice(-130) || '';
}

