/* 组装发给模型的 messages：历史（最近24回合）+ 状态快照 + 当前指令 */
function buildMessages(s, command, rolls = null) {
  const hist = (s.history || []).slice(-24).flatMap(h => [
    { role: 'user', content: h.u },
    { role: 'assistant', content: h.a },
  ]);
  return [...hist, { role: 'user', content: `${buildSnapshot(s, rolls)}\n\n【玩家指令】${command}` }];
}

